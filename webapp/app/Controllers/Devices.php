<?php

namespace App\Controllers;

use App\Libraries\Inventory\AddressService;
use App\Libraries\Inventory\Inventory;
use App\Libraries\Inventory\LoginTagSuggestion;
use App\Libraries\Nodes\NodeConfigSync;
use App\Libraries\Nodes\NodeSettings;
use App\Libraries\Rules\RuleRunner;
use CodeIgniter\Exceptions\PageNotFoundException;
use CodeIgniter\HTTP\RedirectResponse;
use InvalidArgumentException;

/**
 * SMTP logins (SMTP AUTH on ports 587/465), one per component of a device (E-024): user name freely
 * chosen, linked to a device, with fixed tags ("capture tags" suggests them from the name).
 * Passwords are generated by the app, shown exactly once (in the response to the POST, never stored
 * in the session) and stored only as bcrypt hash.
 */
class Devices extends BaseController
{
    protected $helpers = ['ravenkeep', 'url', 'form'];

    public function index(?array $created = null): string
    {
        $db = db_connect();
        if ($created !== null) {
            // the page shows a plain password: never cache it
            $this->response->setHeader('Cache-Control', 'no-store, max-age=0');
        }

        $tags = [];
        foreach ($db->table('smtp_identity_tags st')->select('st.identity_id, t.name')->join('tags t', 't.id = st.tag_id')->orderBy('t.name')->get()->getResultArray() as $t) {
            $tags[(int) $t['identity_id']][] = $t['name'];
        }

        return view('devices/index', [
            'identities' => $db->table('smtp_identities s')->select('s.*, d.name AS device_name, d.path AS device_path, c.name AS customer_name')
                ->join('devices d', 'd.id = s.device_id', 'left')->join('customers c', 'c.id = d.customer_id', 'left')
                ->orderBy('s.username')->get()->getResultArray(),
            'identityTags' => $tags,
            'devices'    => $this->devices(),
            'domains'    => array_column($db->table('local_domains')->select('domain')->orderBy('domain')->get()->getResultArray(), 'domain'),
            'created'    => $created,
            'lastSeen'   => $this->lastSeen(),
        ]);
    }

    public function create(): RedirectResponse|string
    {
        $db       = db_connect();
        $settings = new NodeSettings($db);

        try {
            [$id, $password] = $settings->createIdentity((string) $this->request->getPost('local_part'), (string) $this->request->getPost('domain'),
                trim((string) $this->request->getPost('note')) ?: null, ((int) $this->request->getPost('device_id')) ?: null);
        } catch (InvalidArgumentException $e) {
            return redirect()->to(site_url('devices'))->with('error', lang('Devices.invalid_' . $e->getMessage()));
        }
        $username = $db->table('smtp_identities')->select('username')->where('id', $id)->get()->getRow()->username;
        (new RuleRunner($db))->bumpVersion();

        return $this->index(['id' => $id, 'username' => $username, 'password' => $password, 'sync' => $this->sync()]);
    }

    /** Edit a login: device, fixed tags, note – with the suggestion read from its name (E-024). */
    public function edit(int $id): string
    {
        $db       = db_connect();
        $identity = $db->table('smtp_identities')->where('id', $id)->get()->getRowArray() ?? throw PageNotFoundException::forPageNotFound();
        $runner   = new RuleRunner($db);
        $known    = (new Inventory($db, $runner))->addressLookup();
        $own      = array_column($db->table('smtp_identity_tags st')->select('t.name')->join('tags t', 't.id = st.tag_id')
            ->where('st.identity_id', $id)->orderBy('t.name')->get()->getResultArray(), 'name');
        $suggest  = LoginTagSuggestion::suggest($identity['username'], $known);
        $deviceId = $suggest['device'] === null ? null : (int) ($db->table('devices')->select('id')->where('path', $suggest['device'])->get()->getRow()->id ?? 0);

        return view('devices/edit', [
            'identity'   => $identity,
            'own'        => $own,
            'suggest'    => $suggest + ['device_id' => $deviceId],
            'devices'    => $this->devices(),
            'deviceTags' => $identity['device_id'] ? (new Inventory($db, $runner))->deviceTags((int) $identity['device_id']) : [],
            'tagNames'   => array_column($db->table('tags')->select('name')->orderBy('name')->get()->getResultArray(), 'name'),
        ]);
    }

    public function save(int $id): RedirectResponse
    {
        try {
            (new NodeSettings(db_connect()))->setIdentity($id, ((int) $this->request->getPost('device_id')) ?: null,
                preg_split('/[\s,]+/', (string) $this->request->getPost('tags'), -1, PREG_SPLIT_NO_EMPTY) ?: [],
                trim((string) $this->request->getPost('note')) ?: null);
        } catch (InvalidArgumentException $e) {
            $key = 'Customers.invalid_' . $e->getMessage();

            return redirect()->to(site_url('devices/' . $id))->with('error', lang($key) !== $key ? lang($key) : lang('Devices.invalid_' . $e->getMessage()));
        }

        return redirect()->to(site_url('devices'))->with('success', lang('Customers.saved'));
    }

    /** Create a value missing in the inventory, named by the login (customer, device, location, source). */
    public function createPart(int $id): RedirectResponse
    {
        $db       = db_connect();
        $identity = $db->table('smtp_identities')->where('id', $id)->get()->getRowArray() ?? throw PageNotFoundException::forPageNotFound();

        try {
            (new AddressService($db, new RuleRunner($db)))->create($identity['username'], (string) $this->request->getPost('kind'), (string) $this->request->getPost('value'));
        } catch (InvalidArgumentException $e) {
            $key = 'Customers.invalid_' . $e->getMessage();

            return redirect()->to(site_url('devices/' . $id))->with('error', lang($key) !== $key ? lang($key) : lang('Addresses.invalid', [$e->getMessage()]));
        }

        return redirect()->to(site_url('devices/' . $id))->with('success', lang('Addresses.created'));
    }

    /** @return list<array> all devices for the selection, by customer */
    private function devices(): array
    {
        return db_connect()->table('devices d')->select('d.id, d.path, d.name, c.name AS customer_name')
            ->join('customers c', 'c.id = d.customer_id')->orderBy('c.name')->orderBy('d.name')->get()->getResultArray();
    }

    public function password(int $id): RedirectResponse|string
    {
        $row = db_connect()->table('smtp_identities')->where('id', $id)->get()->getRowArray();
        if ($row === null) {
            return redirect()->to(site_url('devices'));
        }
        $password = (new NodeSettings(db_connect()))->resetPassword($id);

        return $this->index(['username' => $row['username'], 'password' => $password, 'sync' => $this->sync(), 'reset' => true]);
    }

    public function toggle(int $id): RedirectResponse
    {
        (new NodeSettings(db_connect()))->toggleIdentity($id);

        return redirect()->to(site_url('devices'))->with('success', $this->sync());
    }

    public function delete(int $id): RedirectResponse
    {
        (new NodeSettings(db_connect()))->deleteIdentity($id);
        (new RuleRunner(db_connect()))->bumpVersion();

        return redirect()->to(site_url('devices'))->with('success', lang('Devices.deleted') . ' ' . $this->sync());
    }

    private function sync(): string
    {
        $errors = array_filter((new NodeConfigSync(db_connect()))->syncAll(), static fn ($r) => str_starts_with($r, 'error'));

        return $errors === [] ? lang('Senders.nodesUpdated') : lang('Senders.nodesError', [implode(', ', array_keys($errors))]);
    }

    /**
     * Last received message per SMTP login (shows whether a device actually sends).
     *
     * @return array<string, string>
     */
    private function lastSeen(): array
    {
        $rows = db_connect()->table('messages')->select('sasl_username, MAX(received_at) AS last')
            ->where('mode', 'auth')->groupBy('sasl_username')->get()->getResultArray();

        return array_column($rows, 'last', 'sasl_username');
    }
}

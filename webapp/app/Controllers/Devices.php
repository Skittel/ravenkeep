<?php

namespace App\Controllers;

use App\Libraries\Inventory\AddressService;
use App\Libraries\Inventory\Inventory;
use App\Libraries\Inventory\LoginTagSuggestion;
use App\Libraries\Mailrunner\MailrunnerClient;
use App\Libraries\Mailrunner\SmtpCredentials;
use App\Libraries\Nodes\NodeSettings;
use App\Libraries\Secrets;
use App\Libraries\Rules\RuleRunner;
use CodeIgniter\Exceptions\PageNotFoundException;
use CodeIgniter\HTTP\RedirectResponse;
use InvalidArgumentException;
use RuntimeException;

/**
 * SMTP logins (SMTP AUTH on ports 587/465), one per component of a device (E-024): user name freely
 * chosen, linked to a device, with fixed tags ("capture tags" suggests them from the name).
 * Passwords are generated by the app, shown exactly once (in the response to the POST, never stored
 * in the session) and stored only as bcrypt hash.
 */
class Devices extends BaseController
{
    protected $helpers = ['ravenkeep', 'url', 'form'];

    public function index(?array $created = null): string
    {
        $db = db_connect();
        if ($created !== null) {
            // the page shows a plain password: never cache it
            $this->response->setHeader('Cache-Control', 'no-store, max-age=0');
        }

        $tags = [];
        foreach ($db->table('smtp_identity_tags st')->select('st.identity_id, t.name')->join('tags t', 't.id = st.tag_id')->orderBy('t.name')->get()->getResultArray() as $t) {
            $tags[(int) $t['identity_id']][] = $t['name'];
        }

        return view('devices/index', [
            'identities' => $db->table('smtp_identities s')->select('s.*, d.name AS device_name, d.path AS device_path, c.name AS customer_name')
                ->join('devices d', 'd.id = s.device_id', 'left')->join('customers c', 'c.id = d.customer_id', 'left')
                ->orderBy('s.username')->get()->getResultArray(),
            'identityTags' => $tags,
            'devices'    => $this->devices(),
            'components' => array_map(static fn (string $n): string => substr($n, 7),
                array_column($db->table('tags')->select('name')->like('name', 'source:', 'after')->orderBy('name')->get()->getResultArray(), 'name')),
            'domains'    => array_column($db->table('local_domains')->select('domain')->orderBy('domain')->get()->getResultArray(), 'domain'),
            'created'    => $created,
            'lastSeen'   => $this->lastSeen(),
            'smtpHost'   => (string) parse_url(config('Mailrunner')->url, PHP_URL_HOST),
        ]);
    }

    public function create(): RedirectResponse|string
    {
        try {
            $note = trim((string) $this->request->getPost('note')) ?: null;
            [$id, $password, $username] = $this->request->getPost('mode') === 'custom'
                // exception: free user name, device optional
                ? $this->credentials()->create((string) $this->request->getPost('local_part'), (string) $this->request->getPost('domain'), $note,
                    ((int) $this->request->getPost('device_id')) ?: null, (bool) $this->request->getPost('plaintext_port25'), $this->networks())
                // normal case (E-025): customer.device.component
                : $this->credentials()->createForDevice((int) $this->request->getPost('device_id'), (string) $this->request->getPost('component'),
                    (string) $this->request->getPost('domain'), $note, (bool) $this->request->getPost('plaintext_port25'), $this->networks());
        } catch (InvalidArgumentException $e) {
            return redirect()->to(site_url('devices'))->with('error', $this->error($e));
        } catch (RuntimeException $e) {
            return redirect()->to(site_url('devices'))->with('error', lang('Devices.mailrunnerError', [$e->getMessage()]));
        }

        return $this->index(['id' => $id, 'username' => $username, 'password' => $password]);
    }

    /** Edit a login: device, fixed tags, note – with the suggestion read from its name (E-024). */
    /**
     * Show the access data (server, ports, user name, stored password). POST, so only users with write
     * access (rw) see the password; the page is not cached.
     */
    public function showCredentials(int $id): string
    {
        $this->response->setHeader('Cache-Control', 'no-store, max-age=0');
        try {
            $row      = db_connect()->table('smtp_identities')->select('password_enc')->where('id', $id)->get()->getRowArray()
                ?? throw PageNotFoundException::forPageNotFound();
            $password = $row['password_enc'] === null ? null : Secrets::fromConfig()->decrypt($row['password_enc']);
        } catch (RuntimeException $e) {
            $password = null; // login from before 0.3.23 or key missing: a new password has to be set
        }

        return $this->edit($id, ['password' => $password]);
    }

    public function edit(int $id, ?array $access = null): string
    {
        $db       = db_connect();
        $identity = $db->table('smtp_identities')->where('id', $id)->get()->getRowArray() ?? throw PageNotFoundException::forPageNotFound();
        $runner   = new RuleRunner($db);
        $known    = (new Inventory($db, $runner))->addressLookup();
        $own      = array_column($db->table('smtp_identity_tags st')->select('t.name')->join('tags t', 't.id = st.tag_id')
            ->where('st.identity_id', $id)->orderBy('t.name')->get()->getResultArray(), 'name');
        $suggest  = LoginTagSuggestion::suggest($identity['username'], $known);
        $deviceId = $suggest['device'] === null ? null : (int) ($db->table('devices')->select('id')->where('path', $suggest['device'])->get()->getRow()->id ?? 0);

        return view('devices/edit', [
            'identity'   => $identity,
            'own'        => $own,
            'suggest'    => $suggest + ['device_id' => $deviceId],
            'devices'    => $this->devices(),
            'deviceTags' => $identity['device_id'] ? (new Inventory($db, $runner))->deviceTags((int) $identity['device_id']) : [],
            // all tags, including those of customers, locations and devices without any message yet
            'tagNames'   => $this->allTagNames(),
            'access'     => $access === null ? null : $access + [
                'host' => (string) parse_url(config('Mailrunner')->url, PHP_URL_HOST), 'username' => $identity['username'],
            ],
        ]);
    }

    public function save(int $id): RedirectResponse
    {
        try {
            (new NodeSettings(db_connect()))->setIdentity($id, ((int) $this->request->getPost('device_id')) ?: null,
                preg_split('/[\s,]+/', (string) $this->request->getPost('tags'), -1, PREG_SPLIT_NO_EMPTY) ?: [],
                trim((string) $this->request->getPost('note')) ?: null);
            if ($this->request->getPost('options') !== null) { // full edit form (not "apply suggestion")
                $this->credentials()->updateOptions($id, (bool) $this->request->getPost('plaintext_port25'), $this->networks());
            }
        } catch (RuntimeException $e) {
            return redirect()->to(site_url('devices/' . $id))->with('error', lang('Devices.mailrunnerError', [$e->getMessage()]));
        } catch (InvalidArgumentException $e) {
            $key = 'Customers.invalid_' . $e->getMessage();

            return redirect()->to(site_url('devices/' . $id))->with('error', lang($key) !== $key ? lang($key) : lang('Devices.invalid_' . $e->getMessage()));
        }

        return redirect()->to(site_url('devices'))->with('success', lang('Customers.saved'));
    }

    /** Create a value missing in the inventory, named by the login (customer, device, location, source). */
    public function createPart(int $id): RedirectResponse
    {
        $db       = db_connect();
        $identity = $db->table('smtp_identities')->where('id', $id)->get()->getRowArray() ?? throw PageNotFoundException::forPageNotFound();

        try {
            // path form customer.device.component (E-025): give the address service the scheme form for the customer
            $address = preg_replace('/^([a-z0-9-]+)\.([a-z0-9-]+)\.([a-z0-9-]+)@/', '$2_$3_$1@', $identity['username']);
            (new AddressService($db, new RuleRunner($db)))->create($address, (string) $this->request->getPost('kind'), (string) $this->request->getPost('value'));
        } catch (InvalidArgumentException $e) {
            $key = 'Customers.invalid_' . $e->getMessage();

            return redirect()->to(site_url('devices/' . $id))->with('error', lang($key) !== $key ? lang($key) : lang('Addresses.invalid', [$e->getMessage()]));
        }

        return redirect()->to(site_url('devices/' . $id))->with('success', lang('Addresses.created'));
    }

    /** @return list<string> */
    private function allTagNames(): array
    {
        $db    = db_connect();
        $names = array_unique([...array_column($db->table('tags')->select('name')->get()->getResultArray(), 'name'),
            ...(new Inventory($db, new RuleRunner($db)))->automaticTagNames()]);
        sort($names);

        return array_values($names);
    }

    /** @return list<array> all devices for the selection, by customer */
    private function devices(): array
    {
        return db_connect()->table('devices d')->select('d.id, d.path, d.name, c.name AS customer_name')
            ->join('customers c', 'c.id = d.customer_id')->orderBy('c.name')->orderBy('d.name')->get()->getResultArray();
    }

    /** New password from the node; the old one stays valid for the chosen grace period. */
    public function password(int $id): RedirectResponse|string
    {
        $row = db_connect()->table('smtp_identities')->where('id', $id)->get()->getRowArray();
        if ($row === null) {
            return redirect()->to(site_url('devices'));
        }

        return $this->withPassword($id, fn (SmtpCredentials $c) => $c->rotate($id, (int) $this->request->getPost('grace')), true);
    }

    /** Create a login from before MailRunner on the node. */
    public function register(int $id): RedirectResponse|string
    {
        return $this->withPassword($id, static fn (SmtpCredentials $c) => $c->register($id), false);
    }

    public function toggle(int $id): RedirectResponse
    {
        return $this->change(static fn (SmtpCredentials $c) => $c->toggle($id), lang('Customers.saved'));
    }

    public function delete(int $id): RedirectResponse
    {
        return $this->change(static fn (SmtpCredentials $c) => $c->delete($id), lang('Devices.deleted'));
    }

    protected function credentials(): SmtpCredentials
    {
        return new SmtpCredentials(db_connect(), MailrunnerClient::fromConfig());
    }

    private function withPassword(int $id, callable $fn, bool $reset): RedirectResponse|string
    {
        try {
            $password = $fn($this->credentials());
        } catch (InvalidArgumentException $e) {
            return redirect()->to(site_url('devices'))->with('error', $this->error($e));
        } catch (RuntimeException $e) {
            return redirect()->to(site_url('devices'))->with('error', lang('Devices.mailrunnerError', [$e->getMessage()]));
        }
        $username = db_connect()->table('smtp_identities')->select('username')->where('id', $id)->get()->getRow()->username;

        return $this->index(['id' => $id, 'username' => $username, 'password' => $password, 'reset' => $reset]);
    }

    private function change(callable $fn, string $success): RedirectResponse
    {
        try {
            $fn($this->credentials());
        } catch (InvalidArgumentException $e) {
            return redirect()->to(site_url('devices'))->with('error', $this->error($e));
        } catch (RuntimeException $e) {
            return redirect()->to(site_url('devices'))->with('error', lang('Devices.mailrunnerError', [$e->getMessage()]));
        }

        return redirect()->to(site_url('devices'))->with('success', $success);
    }

    private function error(InvalidArgumentException $e): string
    {
        foreach (['Devices.invalid_', 'Customers.invalid_'] as $prefix) {
            if (lang($prefix . $e->getMessage()) !== $prefix . $e->getMessage()) {
                return lang($prefix . $e->getMessage());
            }
        }

        return lang('Devices.mailrunnerError', [$e->getMessage()]);
    }

    /** @return list<string> */
    private function networks(): array
    {
        return preg_split('/[\s,]+/', (string) $this->request->getPost('allowed_networks'), -1, PREG_SPLIT_NO_EMPTY) ?: [];
    }

    /**
     * Last received message per SMTP login (shows whether a device actually sends).
     *
     * @return array<string, string>
     */
    private function lastSeen(): array
    {
        $rows = db_connect()->table('messages')->select('sasl_username, MAX(received_at) AS last')
            ->where('mode', 'auth')->groupBy('sasl_username')->get()->getResultArray();

        return array_column($rows, 'last', 'sasl_username');
    }
}
